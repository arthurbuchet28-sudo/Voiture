export const inPolygon = (lon: number, lat: number, poly: [number, number][]) => {
	let inside = false;
	for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
		const [xi, yi] = poly[i];
		const [xj, yj] = poly[j];
		if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
	}
	return inside;
};

export const isLand = (lon: number, lat: number) => CONTINENTS.some((p) => inPolygon(lon, lat, p));

/** Points de terre sur une grille régulière (pour une carte « en pointillés »). */
export const landDots = (step: number, latMin = -56, latMax = 78) => {
	const out: [number, number][] = [];
	for (let lat = latMax; lat >= latMin; lat -= step) {
		for (let lon = -180; lon < 180; lon += step) {
			if (isLand(lon, lat)) out.push([lon, lat]);
		}
	}
	return out;
};
